/* eslint-disable antfu/no-top-level-await, no-console -- Desktop acceptance owns its processes. */
import assert from 'node:assert/strict'
import { mkdir, mkdtemp, readFile, writeFile } from 'node:fs/promises'
import { join, resolve } from 'node:path'
import process from 'node:process'
import { _electron } from 'playwright'
import { desktopLaunch } from './desktop-launch.mjs'

const data = await mkdtemp(resolve('.data/onboarding-'))
const workspace = join(data, 'project')
await mkdir(workspace)
const readonlyWorkspace = join(data, '只读 项目')
await mkdir(readonlyWorkspace)
const script = join(data, 'script.json')
await writeFile(script, JSON.stringify([{ text: '你好，我们开始吧。' }]))
const desktop = await _electron.launch(desktopLaunch(data, { ANNA_TEST_SCRIPT: script, ANNA_TEST_KEY: 'scripted', ANNA_TEST_FAKE_AGENT: resolve('tests/fixtures/fake-agent.mjs'), ANNA_TEST_NODE: process.execPath }))
try {
  const page = await desktop.firstWindow()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  const flow = page.getByRole('dialog', { name: 'Anna 档案' })
  await flow.waitFor()
  assert.equal(await flow.getByRole('button', { name: '2 选择大脑' }).isDisabled(), true)
  // Only the OS dialog is stubbed; the user's button, IPC and Host path validation run normally.
  await desktop.evaluate(({ dialog }) => { dialog.showOpenDialog = async () => ({ canceled: true, filePaths: [] }) })
  await flow.getByRole('button', { name: '选择工作目录…' }).click()
  let cancelled = await page.evaluate(() => window.anna.invoke({ type: 'snapshot' }))
  assert(cancelled.ok)
  assert.equal(cancelled.snapshot.settings.workspace, undefined)
  await flow.getByRole('heading', { name: '先为我们选一个工作目录' }).waitFor()
  await desktop.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }) }, readonlyWorkspace)
  await flow.getByRole('button', { name: '选择工作目录…' }).click()
  await flow.getByRole('button', { name: '先只读看看', exact: true }).click()
  cancelled = await page.evaluate(() => window.anna.invoke({ type: 'snapshot' }))
  assert(cancelled.ok)
  assert.equal(cancelled.snapshot.mode, 'plan')
  assert.equal(cancelled.snapshot.workspace.trusted, false)
  await desktop.evaluate(({ dialog }, path) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] }) }, workspace)
  await flow.getByRole('button', { name: '选择工作目录…' }).click()
  await flow.getByRole('button', { name: '信任这个文件夹', exact: true }).click()
  await flow.getByRole('button', { name: '下一步：选择大脑' }).click()
  await flow.getByRole('radio', { name: /pi.*默认/ }).waitFor()
  await flow.getByRole('button', { name: '选择其他大脑', exact: true }).click()
  assert(await flow.locator('.brain-tile').count() > 15)
  const missing = flow.locator('.brain-tile.unavailable [role=radio]')
  assert(await missing.count() > 0)
  assert.equal(await missing.first().isDisabled(), true)
  await flow.getByRole('button', { name: '确认大脑，接通模型' }).click()
  await flow.getByRole('button', { name: '验证连接（少量调用）' }).click()
  await flow.getByRole('button', { name: '下一步：认识彼此' }).click()
  await flow.getByRole('textbox', { name: '怎么称呼你（选填）' }).waitFor()
  await page.reload()
  await flow.getByRole('textbox', { name: '怎么称呼你（选填）' }).waitFor()
  await flow.getByRole('textbox', { name: '怎么称呼你（选填）' }).fill('小麦')
  await flow.getByRole('radio', { name: /好奇探索者/ }).click()
  await page.locator('.model-canvas[data-state="ready"]').waitFor({ timeout: 30000 })
  const stage = await page.locator('.stage').boundingBox()
  const card = await flow.boundingBox()
  assert(stage.x + stage.width <= card.x, 'Onboarding must leave Anna visible beside the guide')
  await page.screenshot({ animations: 'disabled', path: 'artifacts/onboarding-personality.png' })
  await flow.getByRole('button', { name: '准备好了，唤醒 Anna' }).click()
  await flow.getByRole('heading', { name: '我们先做一件小事' }).waitFor()
  assert.equal(await flow.getByRole('button').filter({ hasText: '只读查看这个工作文件夹' }).count(), 1)
  await flow.getByRole('button', { name: '先和 Anna 聊聊', exact: true }).click()
  await flow.waitFor({ state: 'detached' })
  let reply = await page.evaluate(() => window.anna.invoke({ type: 'snapshot' }))
  assert(reply.ok)
  assert.equal(reply.snapshot.settings.onboardingComplete, true)
  assert.equal(reply.snapshot.settings.personality.type, 'ENTP')
  assert.equal(reply.snapshot.settings.personality.nickname, '小麦')
  assert(Array.isArray(reply.snapshot.skills))
  await page.reload()
  await page.locator('.brain-chip').waitFor()
  assert.equal(await flow.count(), 0)
  await page.locator('.brain-chip').click()
  await flow.getByRole('button', { name: '生命状态', exact: true }).click()
  await flow.getByRole('heading', { name: 'Anna 此刻的状态' }).waitFor()
  await page.screenshot({ animations: 'disabled', path: 'artifacts/life-status.png' })
  assert.deepEqual(errors, [])
  const saved = JSON.parse(await readFile(join(data, 'settings.json'), 'utf8'))
  assert.equal(saved.personality.nickname, '小麦')
  reply = await page.evaluate(() => window.anna.invoke({ type: 'share-pi-model' }))
  assert(reply.ok, reply.error)
  reply = await page.evaluate(() => window.anna.invoke({ type: 'share-pi-model', restore: true }))
  assert(reply.ok, reply.error)
  assert.equal(reply.snapshot.settings.sharedModelBackup, undefined)
  await flow.getByRole('button', { name: '其他会话', exact: true }).click()
  await flow.getByLabel('来自哪个大脑').selectOption('codex')
  await flow.getByRole('button', { name: '读取历史列表', exact: true }).click()
  await flow.getByText('外部原始任务', { exact: true }).waitFor()
  await flow.getByRole('button', { name: '预览会话', exact: true }).click()
  await flow.getByText('原 agent 的工作结果', { exact: false }).waitFor()
  await page.screenshot({ animations: 'disabled', path: 'artifacts/history-preview.png' })
  await flow.getByRole('button', { name: '确认创建 Anna 分支', exact: true }).click()
  await page.waitForFunction(() => [...document.querySelectorAll('button')].some(button => button.textContent === '确认创建 Anna 分支' && !button.disabled))
  reply = await page.evaluate(() => window.anna.invoke({ type: 'snapshot' }))
  assert(reply.ok)
  assert.equal(reply.snapshot.sessionId, 'anna-forked-thread')
  assert.equal(reply.snapshot.settings.kernel, 'codex')
  assert(reply.snapshot.messages.some(message => message.text.includes('此前内容来自原 agent')))
  await flow.getByRole('button', { name: '生命状态', exact: true }).click()
  await flow.getByRole('button', { name: '刷新能力报告', exact: true }).click()
  await flow.getByText('测试工作方法', { exact: true }).waitFor()
  await flow.getByText('已发现、未验证', { exact: false }).waitFor()
  await flow.getByRole('button', { name: '刷新账号额度', exact: true }).click()
  await flow.getByText('codex · 15 分钟已用 25%', { exact: true }).waitFor()
  await flow.getByText('secondary · 15 分钟已用 30%', { exact: true }).waitFor()
  await page.screenshot({ animations: 'disabled', path: 'artifacts/capability-report.png' })
  assert.deepEqual(errors, [])
  await page.reload()
  await page.locator('.brain-chip').waitFor()
  reply = await page.evaluate(() => window.anna.invoke({ type: 'connect' }))
  assert(reply.ok)
  assert.equal(reply.snapshot.sessionId, 'anna-forked-thread')
  assert(reply.snapshot.messages.some(message => message.text.includes('此前内容来自原 agent')))
  await writeFile(script, JSON.stringify([{ tools: [{ name: 'anna_memory', args: { action: 'remember', text: '喜欢绿茶' } }] }, { text: '我记下了你确认的偏好。' }]))
  reply = await page.evaluate(() => window.anna.invoke({ type: 'kernel', id: 'pi' }))
  assert(reply.ok)
  const pending = page.evaluate(() => window.anna.invoke({ type: 'send', text: '聊聊我喜欢的茶' }))
  const candidate = page.locator('.approval-request')
  await candidate.getByLabel('准备记住的内容').fill('喜欢淡一点的绿茶')
  await candidate.getByRole('combobox', { name: '记忆分类', exact: true }).selectOption('preference')
  await page.screenshot({ animations: 'disabled', path: 'artifacts/memory-candidate.png' })
  await candidate.getByRole('button', { name: '确认记住', exact: true }).click()
  assert((await pending).ok)
  await page.locator('.brain-chip').click()
  await flow.getByRole('button', { name: '共同记忆', exact: true }).click()
  await flow.getByText('喜欢淡一点的绿茶', { exact: true }).waitFor()
  await flow.getByRole('button', { name: '修改记忆', exact: true }).click()
  await flow.getByLabel('记忆内容').fill('喜欢红茶')
  await flow.getByRole('button', { name: '保存修改', exact: true }).click()
  await flow.getByText('喜欢红茶', { exact: true }).waitFor()
  await flow.getByRole('button', { name: '忘记', exact: true }).click()
  await flow.getByText('还没有记忆，可以告诉 Anna“记住：……”', { exact: true }).waitFor()
  assert.deepEqual(errors, [])
  console.log('Onboarding: native folder selection, trust, brain cards, personality, reload, real skill counts, sharing and restore passed.')
}
finally { await desktop.close() }
